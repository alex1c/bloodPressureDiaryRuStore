/**
 * Patches the generated Expo android/ Gradle project to use a production
 * release keystore instead of the debug keystore.
 *
 * Expo CNG always emits `signingConfig signingConfigs.debug` on the release
 * build type. That is why current store-shaped artifacts are debug-signed.
 *
 * This script:
 * - reads gitignored credentials/keystore.properties
 * - copies it to android/keystore.properties
 * - injects a `release` signingConfig and points buildTypes.release at it
 *
 * It never creates a keystore, never invents passwords, and refuses to run
 * if the properties file or storeFile is missing.
 */
const fs = require('node:fs')
const path = require('node:path')

const MARKER = '// CALCULATOR_FOUNDATION_RELEASE_SIGNING (generated by scripts/apply-release-signing.cjs)'

const root = path.resolve(__dirname, '..')
const propertiesSrc = path.join(root, 'credentials', 'keystore.properties')
const androidDir = path.join(root, 'android')
const propertiesDest = path.join(androidDir, 'keystore.properties')
const appBuildGradle = path.join(androidDir, 'app', 'build.gradle')

function fail(message) {
	console.error(message)
	process.exit(1)
}

function parseProperties(filePath) {
	const text = fs.readFileSync(filePath, 'utf8')
	/** @type {Record<string, string>} */
	const values = {}
	for (const rawLine of text.split(/\r?\n/)) {
		const line = rawLine.trim()
		if (!line || line.startsWith('#') || !line.includes('=')) {
			continue
		}
		const eq = line.indexOf('=')
		values[line.slice(0, eq).trim()] = line.slice(eq + 1).trim()
	}
	return values
}

if (!fs.existsSync(propertiesSrc)) {
	const envProps = require('./check-signing-credentials.cjs').resolveFromEnv()
	if (envProps) {
		const lines = [
			'# Generated from BP_DIARY_* environment variables — do not commit.',
			`storeFile=${envProps.storeFile.replace(/\\/g, '/')}`,
			`storePassword=${envProps.storePassword}`,
			`keyAlias=${envProps.keyAlias}`,
			`keyPassword=${envProps.keyPassword}`,
			'',
		]
		fs.mkdirSync(path.dirname(propertiesSrc), { recursive: true })
		fs.writeFileSync(propertiesSrc, lines.join('\n'), 'utf8')
		console.log('Created credentials/keystore.properties from environment variables.')
	} else {
		fail(
			[
				'Missing credentials/keystore.properties.',
				'Generate the production keystore first (see credentials/README.md),',
				'then copy credentials/keystore.properties.example and fill in local values,',
				'or export BP_DIARY_KEYSTORE_PATH / BP_DIARY_KEYSTORE_PASSWORD /',
				'BP_DIARY_KEY_ALIAS / BP_DIARY_KEY_PASSWORD.',
				'Passwords must be chosen by you — they are not stored in git.',
			].join('\n'),
		)
	}
}

if (!fs.existsSync(androidDir) || !fs.existsSync(appBuildGradle)) {
	fail('Generated android/ project not found. Run production prebuild first.')
}

const props = parseProperties(propertiesSrc)
for (const key of ['storeFile', 'storePassword', 'keyAlias', 'keyPassword']) {
	if (!props[key] || props[key].includes('REPLACE_ME') || props[key].includes('YOUR_USER')) {
		fail(`credentials/keystore.properties is incomplete or still a template (${key}).`)
	}
}

if (!fs.existsSync(props.storeFile)) {
	fail('Keystore file does not exist at storeFile. Check credentials/keystore.properties.')
}

fs.copyFileSync(propertiesSrc, propertiesDest)

let gradle = fs.readFileSync(appBuildGradle, 'utf8')

const loadBlock = `    ${MARKER}
    def releaseKeystoreProperties = new Properties()
    def releaseKeystorePropertiesFile = rootProject.file("keystore.properties")
    if (!releaseKeystorePropertiesFile.exists()) {
        throw new GradleException("android/keystore.properties is missing; refusing to debug-sign a production release.")
    }
    releaseKeystoreProperties.load(new FileInputStream(releaseKeystorePropertiesFile))

`

const releaseConfig = `        release {
            keyAlias releaseKeystoreProperties['keyAlias']
            keyPassword releaseKeystoreProperties['keyPassword']
            storeFile file(releaseKeystoreProperties['storeFile'])
            storePassword releaseKeystoreProperties['storePassword']
        }
`

if (!gradle.includes(MARKER)) {
	const signingIdx = gradle.indexOf('    signingConfigs {')
	if (signingIdx === -1) {
		fail('android/app/build.gradle has no signingConfigs block to patch.')
	}
	gradle = gradle.slice(0, signingIdx) + loadBlock + gradle.slice(signingIdx)

	const debugBlockEnd = gradle.indexOf('        }\n    }', signingIdx)
	const debugClose = gradle.indexOf(
		'            keyPassword \'android\'\n        }',
	)
	if (debugClose === -1) {
		fail('Could not find debug signingConfig block to insert release config after.')
	}
	const insertAt = debugClose + '            keyPassword \'android\'\n        }'.length
	gradle = `${gradle.slice(0, insertAt)}\n${releaseConfig}${gradle.slice(insertAt)}`

	const releaseHeader = '        release {\n'
	const releaseIdx = gradle.lastIndexOf(releaseHeader)
	if (releaseIdx === -1) {
		fail('Could not find buildTypes.release in android/app/build.gradle.')
	}
	const debugSignInRelease = gradle.indexOf('signingConfig signingConfigs.debug', releaseIdx)
	if (debugSignInRelease === -1) {
		fail('Could not find signingConfig signingConfigs.debug inside buildTypes.release.')
	}
	gradle =
		gradle.slice(0, debugSignInRelease) +
		'signingConfig signingConfigs.release' +
		gradle.slice(debugSignInRelease + 'signingConfig signingConfigs.debug'.length)
}

fs.writeFileSync(appBuildGradle, gradle, 'utf8')
console.log('Applied production signingConfig to android/app/build.gradle.')
console.log(`Release alias: ${props.keyAlias}`)
console.log('Keystore file: present (path not printed).')
console.log('Next: cd android && .\\gradlew.bat bundleRelease')
console.log('Then: npm run verify:release-signing -- android/app/build/outputs/bundle/release/app-release.aab')
